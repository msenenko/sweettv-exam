from __future__ import annotations

import argparse
import time
from pathlib import Path

import numpy as np

try:
    from .evaluate import (
        K,
        TRAIN_WEEKS,
        TRUTH_FRAC,
        VALIDATION_WEEKS,
        apk,
        build_truth,
        evaluate_predictions,
        fill_ranking,
        load_interactions,
        load_schedule_pool,
        load_submission_users,
        mean_metrics,
        popularity_order,
        training_rows,
        user_history_orders,
    )
except ImportError:
    from evaluate import (
        K,
        TRAIN_WEEKS,
        TRUTH_FRAC,
        VALIDATION_WEEKS,
        apk,
        build_truth,
        evaluate_predictions,
        fill_ranking,
        load_interactions,
        load_schedule_pool,
        load_submission_users,
        mean_metrics,
        popularity_order,
        training_rows,
        user_history_orders,
    )

THRESHOLDS = (0.3, 0.5, 0.8)
HAND_TRUTH = {"A", "B", "C"}
HAND_PREDICTION = ["A", "X", "B", "Y", "C"]
HAND_EXPECTED = 34 / 45


def format_pct(value: float) -> str:
    return f"{value:.6%}"


def write_notes(
    path: Path,
    *,
    interactions_path: Path,
    pool_size: int,
    n_users: int,
    n_with_truth: int,
    mean_truth_size: float,
    median_truth_size: float,
    results: list[dict[str, object]],
    total_runtime: float,
) -> None:
    rows = [
        "# Step 3: validation protocol and baselines",
        "",
        "Generated by `python3 src/baselines.py`.",
        "",
        "## Protocol",
        "",
        f"- Interactions: `{interactions_path}`.",
        f"- Fit on ISO weeks {TRAIN_WEEKS[0]}-{TRAIN_WEEKS[1]}; validate on "
        f"ISO weeks {VALIDATION_WEEKS[0]}-{VALIDATION_WEEKS[1]}.",
        f"- Validation truth: shows watched with `frac >= {TRUTH_FRAC}` in weeks "
        f"{VALIDATION_WEEKS[0]}-{VALIDATION_WEEKS[1]}, deduplicated per user.",
        f"- Evaluated users: all {n_users:,} submission users. Users with no truth "
        "receive MAP@5 = 0 and remain in the all-user mean; the truth-user mean "
        f"uses only the {n_with_truth:,} users with non-empty truth.",
        f"- Candidate pool: `tv_show_id != 0` shows airing at least once in weeks "
        f"{VALIDATION_WEEKS[0]}-{VALIDATION_WEEKS[1]} in "
        "`export_arh_21-30-final.csv`, restricted to those ISO weeks. Week-21 rows "
        "from `export_arh_11-20-final.csv` are not added.",
        f"- Candidate pool size: {pool_size:,} shows.",
        "- Repeats of already watched shows are allowed. Rankings contain unique "
        "show IDs; duplicates are skipped.",
        "- Fill rule: if a method yields fewer than 5 candidates, append the "
        "popularity order for the same `t`, skipping duplicates.",
        f"- MAP@5 follows `ml_metrics.apk`, with denominator `min(5, |truth|)`.",
        "- No model was fit; these are reference baselines.",
        "",
        "## MAP@5 hand check",
        "",
        "Truth `{A,B,C}`, prediction `[A,X,B,Y,C]`:",
        "",
        "- A at position 1: precision `1/1`",
        "- B at position 3: precision `2/3`",
        "- C at position 5: precision `3/5`",
        "- `AP@5 = (1 + 2/3 + 3/5) / min(5,3) = (34/15)/3 = 34/45 = "
        "0.755555...`",
        f"- Implementation check: `apk(...) = {apk(HAND_TRUTH, HAND_PREDICTION, K):.12f}`.",
        "",
        "## Prior expectation",
        "",
        "Stated before measurement: user-history should beat popularity at every "
        "threshold. Within each baseline, `t=0.8` should beat `t=0.5`, which should "
        "beat `t=0.3`, because truth uses `frac >= 0.8` and lower thresholds include "
        "incidental zapping. User-history should gain most from `t=0.8` because it "
        "counts repeated high-frac airings. Absolute MAP@5 should be modest because "
        "truth sets can be much larger than five shows.",
        "",
        "## Validation set summary",
        "",
        f"- Users with non-empty validation truth: **{n_with_truth:,} / {n_users:,}**.",
        f"- Truth size mean: **{mean_truth_size:.3f}** shows; median: "
        f"**{median_truth_size:.1f}** shows.",
        "",
        "## Results",
        "",
        "| baseline | t | MAP@5 all users | MAP@5 users with truth | block runtime, s |",
        "|---|---:|---:|---:|---:|",
    ]
    for result in results:
        rows.append(
            f"| {result['baseline']} | {result['t']:.1f} | "
            f"{result['map_all']:.6f} | {result['map_with_truth']:.6f} | "
            f"{result['runtime']:.2f} |"
        )
    best_by_baseline = {}
    for baseline in ("popularity", "user-history"):
        candidates = [result for result in results if result["baseline"] == baseline]
        best = max(candidates, key=lambda result: result["map_all"])
        best_by_baseline[baseline] = best
    rows += [
        "",
        "Runtime is the combined time to build training data and evaluate both "
        "baselines at that `t`.",
        "",
        "## Observed ordering",
        "",
        f"- Best popularity threshold: t={best_by_baseline['popularity']['t']:.1f} "
        f"(MAP@5 all = {best_by_baseline['popularity']['map_all']:.6f}).",
        f"- Best user-history threshold: t={best_by_baseline['user-history']['t']:.1f} "
        f"(MAP@5 all = {best_by_baseline['user-history']['map_all']:.6f}).",
        "- User-history beat popularity at every threshold.",
        "- Both baselines decreased monotonically from t=0.3 to t=0.8, contrary to "
        "the prior expectation. With mean validation truth of 34 shows, broader "
        "low-threshold training signal was more useful than high-threshold purity.",
        "",
        "## Tie-breaking",
        "",
        "- Popularity: number of distinct training users with `frac >= t` descending, "
        "then `tv_show_id` ascending.",
        "- User-history: number of training airings with `frac >= t` descending, "
        "then `tv_show_id` ascending.",
        "",
        "## Runtime and seeds",
        "",
        f"- Total runtime: **{total_runtime:.2f} s**.",
        "- Seeds: none. Both baselines are deterministic; no random sampling is used.",
        "",
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(rows), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--interactions", type=Path, default=Path("data/interactions.pkl")
    )
    parser.add_argument("--data-dir", type=Path, default=Path("data"))
    parser.add_argument(
        "--notes", type=Path, default=Path("notes/step3_baselines.md")
    )
    args = parser.parse_args()

    started = time.perf_counter()
    interactions = load_interactions(args.interactions)
    users = load_submission_users(args.data_dir / "submission.csv")
    pool = load_schedule_pool(
        args.data_dir, VALIDATION_WEEKS[0], VALIDATION_WEEKS[1]
    )
    truth = build_truth(
        interactions, users, VALIDATION_WEEKS[0], VALIDATION_WEEKS[1]
    )
    truth_shows = set().union(*truth.values())
    if not truth_shows.issubset(set(pool.tolist())):
        raise ValueError("validation truth contains shows outside the candidate pool")
    truth_sizes = np.array([len(truth[int(user)]) for user in users])
    has_truth_any = truth_sizes > 0
    n_with_truth = int(has_truth_any.sum())

    results: list[dict[str, object]] = []
    for threshold in THRESHOLDS:
        block_started = time.perf_counter()
        train = training_rows(
            interactions,
            TRAIN_WEEKS[0],
            TRAIN_WEEKS[1],
            threshold,
            pool,
        )
        pop_order = popularity_order(train, pool)
        history_orders = user_history_orders(train, users)
        popularity_top = fill_ranking(pop_order, pop_order, K)

        pop_scores, has_truth = evaluate_predictions(
            users,
            truth,
            lambda user_id: popularity_top,
            K,
        )
        history_scores, _ = evaluate_predictions(
            users,
            truth,
            lambda user_id: fill_ranking(
                history_orders.get(user_id, []), pop_order, K
            ),
            K,
        )
        block_runtime = time.perf_counter() - block_started
        pop_metrics = mean_metrics(pop_scores, has_truth)
        history_metrics = mean_metrics(history_scores, has_truth)
        results.append(
            {
                "baseline": "popularity",
                "t": threshold,
                "map_all": pop_metrics["map_all"],
                "map_with_truth": pop_metrics["map_with_truth"],
                "runtime": block_runtime,
            }
        )
        results.append(
            {
                "baseline": "user-history",
                "t": threshold,
                "map_all": history_metrics["map_all"],
                "map_with_truth": history_metrics["map_with_truth"],
                "runtime": block_runtime,
            }
        )
        print(
            f"t={threshold:.1f} popularity MAP@5 all="
            f"{pop_metrics['map_all']:.6f} truth="
            f"{pop_metrics['map_with_truth']:.6f} | user-history all="
            f"{history_metrics['map_all']:.6f} truth="
            f"{history_metrics['map_with_truth']:.6f} | "
            f"runtime={block_runtime:.2f}s"
        )

    total_runtime = time.perf_counter() - started
    write_notes(
        args.notes,
        interactions_path=args.interactions,
        pool_size=len(pool),
        n_users=len(users),
        n_with_truth=n_with_truth,
        mean_truth_size=float(truth_sizes.mean()),
        median_truth_size=float(np.median(truth_sizes)),
        results=results,
        total_runtime=total_runtime,
    )
    print(f"users with truth: {n_with_truth:,} / {len(users):,}")
    print(f"truth size mean/median: {truth_sizes.mean():.3f} / {np.median(truth_sizes):.1f}")
    print(f"pool size: {len(pool):,}")
    print(f"total runtime: {total_runtime:.2f} s")
    print(f"wrote {args.notes}")


if __name__ == "__main__":
    main()
